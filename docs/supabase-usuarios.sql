-- Tabela de usuários (leads) usada pelo fluxo SDR.
-- Como usar: Supabase > menu "SQL Editor" > "New query" > cole TUDO isto > botão "Run".
-- Rodar só UMA vez. Não tem nenhuma chave aqui dentro.

CREATE TABLE IF NOT EXISTS public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp DEFAULT now() NOT NULL,
    name text,
    phone varchar,
    session_id varchar,
    last_message timestamp,
    fup boolean DEFAULT true,
    fup_number smallint DEFAULT 0,
    fup_sent timestamp,
    ai_response boolean DEFAULT true
);

COMMENT ON TABLE public.users IS 'Leads que conversam com o agente SDR no WhatsApp.';
COMMENT ON COLUMN public.users.session_id IS 'Identificador da conversa (instância + telefone).';
COMMENT ON COLUMN public.users.fup IS 'true = pode receber mensagens de follow-up.';
COMMENT ON COLUMN public.users.fup_number IS 'Quantos follow-ups já foram enviados.';
COMMENT ON COLUMN public.users.ai_response IS 'false = um humano assumiu; o agente não responde.';

-- Segurança: bloqueia acesso público. O n8n usa a chave "service_role", que ignora esta trava.
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
